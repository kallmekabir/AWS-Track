// Typed client for the CareLine REST API (task graph C8). Every panel reads data
// through `api`; with VITE_USE_MOCKS=true (or no VITE_API_BASE) it talks to the
// in-browser mock in ./mock instead.
import { config } from '../config'
import type {
  ApiErrorBody,
  AskResponse,
  AuditEntry,
  Brief,
  CallRow,
  FairnessResponse,
  HospitalCollection,
  HospitalRoute,
  OutageMeta,
  OutageSummary,
  PriorityResponse,
  ResidentTimeline,
  Task,
  Triage,
} from './types'

export class ApiError extends Error {
  status: number
  code: string
  constructor(status: number, code: string, message: string) {
    super(message)
    this.name = 'ApiError'
    this.status = status
    this.code = code
  }
}

type Opts = { signal?: AbortSignal }

export interface Api {
  getActiveOutage(o?: Opts): Promise<{ outage: OutageMeta | null }>
  startOutage(zoneId: string): Promise<OutageMeta>
  endOutage(outageId: string): Promise<OutageMeta>
  getSummary(outageId: string, o?: Opts): Promise<OutageSummary>
  getPriority(outageId: string, o?: Opts): Promise<PriorityResponse>
  getCalls(outageId: string, o?: Opts): Promise<{ items: CallRow[] }>
  getTimeline(residentId: string, outageId: string, o?: Opts): Promise<ResidentTimeline>
  getHospitalRoute(residentId: string, outageId: string, o?: Opts): Promise<HospitalRoute>
  getTasks(outageId: string, o?: Opts): Promise<{ items: Task[] }>
  ackTask(taskId: string): Promise<Task>
  doneTask(taskId: string): Promise<Task>
  overrideCall(callId: string, triage: Triage, reason: string): Promise<CallRow>
  getAudit(outageId: string, o?: Opts): Promise<{ items: AuditEntry[] }>
  getFairness(outageId: string, o?: Opts): Promise<FairnessResponse>
  copilotBrief(outageId: string, zoneId: string): Promise<Brief>
  copilotAsk(outageId: string, question: string): Promise<AskResponse>
  copilotApprove(outageId: string, briefId: string): Promise<{ tasks: Task[] }>
  getHospitals(o?: Opts): Promise<HospitalCollection>
}

async function request<T>(method: 'GET' | 'POST', path: string, body?: unknown, opts: Opts = {}): Promise<T> {
  const res = await fetch(`${config.apiBase}${path}`, {
    method,
    signal: opts.signal,
    headers: {
      'content-type': 'application/json',
      'x-api-key': config.apiKey,
      'x-operator-id': config.operatorId,
    },
    body: body === undefined ? undefined : JSON.stringify(body),
  })
  if (!res.ok) {
    let code = `HTTP_${res.status}`
    let message = res.statusText || 'Request failed'
    try {
      const err = (await res.json()) as ApiErrorBody
      code = err.error.code
      message = err.error.message
    } catch {
      // Not a C8 error body (API Gateway 403s, for example); keep the HTTP status.
    }
    throw new ApiError(res.status, code, message)
  }
  return (await res.json()) as T
}

const q = encodeURIComponent

const httpApi: Api = {
  getActiveOutage: (o) => request('GET', '/outages/active', undefined, o),
  startOutage: (zoneId) => request('POST', '/outages', { zone_id: zoneId }),
  endOutage: (id) => request('POST', `/outages/${q(id)}/end`),
  getSummary: (id, o) => request('GET', `/outages/${q(id)}/summary`, undefined, o),
  getPriority: (id, o) => request('GET', `/outages/${q(id)}/priority`, undefined, o),
  getCalls: (id, o) => request('GET', `/calls?outage_id=${q(id)}`, undefined, o),
  getTimeline: (rid, id, o) => request('GET', `/residents/${q(rid)}/timeline?outage_id=${q(id)}`, undefined, o),
  getHospitalRoute: (rid, id, o) =>
    request('GET', `/residents/${q(rid)}/hospital-route?outage_id=${q(id)}`, undefined, o),
  // No status filter: the queue shows OPEN and ACK tasks and counts DONE ones.
  getTasks: (id, o) => request('GET', `/tasks?outage_id=${q(id)}`, undefined, o),
  ackTask: (taskId) => request('POST', `/tasks/${q(taskId)}/ack`),
  doneTask: (taskId) => request('POST', `/tasks/${q(taskId)}/done`),
  overrideCall: (callId, triage, reason) => request('POST', `/calls/${q(callId)}/override`, { triage, reason }),
  getAudit: (id, o) => request('GET', `/audit?outage_id=${q(id)}`, undefined, o),
  getFairness: (id, o) => request('GET', `/metrics/fairness?outage_id=${q(id)}`, undefined, o),
  copilotBrief: (id, zoneId) => request('POST', '/copilot/brief', { outage_id: id, zone_id: zoneId }),
  copilotAsk: (id, question) => request('POST', '/copilot/ask', { outage_id: id, question }),
  copilotApprove: (id, briefId) => request('POST', '/copilot/approve', { outage_id: id, brief_id: briefId }),
  // A static file next to the dashboard, generated by scripts/build_geo_data.py.
  getHospitals: async (o) => {
    const res = await fetch('/hospitals.geojson', { signal: o?.signal })
    if (!res.ok) throw new ApiError(res.status, 'HOSPITALS_MISSING', 'hospitals.geojson is missing')
    return (await res.json()) as HospitalCollection
  },
}

let mockApi: Promise<Api> | undefined
function impl(): Promise<Api> {
  if (!config.useMocks) return Promise.resolve(httpApi)
  mockApi ??= import('./mock').then((m) => m.createMockApi())
  return mockApi
}

// Each call resolves the implementation lazily so the mock never ships in a live build's main chunk.
export const api = new Proxy({} as Api, {
  get: (_target, name: keyof Api) =>
    (...args: unknown[]) =>
      impl().then((a) => (a[name] as (...x: unknown[]) => Promise<unknown>)(...args)),
})
